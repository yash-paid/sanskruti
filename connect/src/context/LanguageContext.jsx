const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [currentLang, setCurrentLang] = useState(() => {
    try {
      return localStorage.getItem('connect_lang') || 'en';
    } catch (e) {
      return 'en';
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem('connect_lang', currentLang);
      document.documentElement.lang = currentLang;
    } catch (e) {}
  }, [currentLang]);

  const setLanguage = (langCode) => {
    if (TRANSLATIONS[langCode]) {
      setCurrentLang(langCode);
    }
  };

  const t = (key, fallback = '') => {
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return TRANSLATIONS.en[key] || fallback || key;
  };

  const currentLanguageMeta = LANGUAGES.find((l) => l.code === currentLang) || LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{
        currentLang,
        currentLanguageMeta,
        setLanguage,
        t,
        LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      currentLang: 'en',
      currentLanguageMeta: LANGUAGES[0],
      setLanguage: () => {},
      t: (key, fallback = '') => TRANSLATIONS.en[key] || fallback || key,
      LANGUAGES,
    };
  }
  return context;
}
